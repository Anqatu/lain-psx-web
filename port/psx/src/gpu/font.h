int GetTimInfo(u_long* tim, TIM_IMAGE* timimg)
{
	u_int* rtim = (u_int*)tim;;

	// Check ID
	if ((rtim[0] & 0xff) != 0x10) {
		return 1;
	}

	// Check version
	if (((rtim[0] >> 8) & 0xff) != 0x0) {
		return 2;
	}

	timimg->mode = rtim[1];
	rtim += 2;

	// Clut present?
	if (timimg->mode & 0x8) {

		timimg->crect = /* lain: PsyQ field name */ (RECT16*)&rtim[1];
		timimg->caddr = (u_int*)&rtim[3];

		rtim += rtim[0] >> 2;
	} else {
		timimg->caddr = 0;
	}

	timimg->prect = /* lain: PsyQ field name */ (RECT16*)&rtim[1];
	timimg->paddr = (u_int*)&rtim[3];

	return 0;

}
